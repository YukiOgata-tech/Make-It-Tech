create function mit.log_expense_record_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  activity_action text;
begin
  if tg_op = 'INSERT' then
    activity_action := 'created';
    insert into mit.expense_activity_logs (
      entity_id, expense_id, action, changes, performed_by
    ) values (
      new.entity_id,
      new.id,
      activity_action,
      jsonb_build_object('new', to_jsonb(new)),
      new.created_by
    );
    return new;
  end if;

  activity_action := case
    when old.status <> 'confirmed' and new.status = 'confirmed' then 'confirmed'
    when old.status <> 'archived' and new.status = 'archived' then 'archived'
    when old.status = 'archived' and new.status <> 'archived' then 'restored'
    else 'updated'
  end;

  insert into mit.expense_activity_logs (
    entity_id, expense_id, action, changes, performed_by
  ) values (
    new.entity_id,
    new.id,
    activity_action,
    jsonb_build_object('old', to_jsonb(old), 'new', to_jsonb(new)),
    new.updated_by
  );
  return new;
end;
$$;

revoke all on function mit.log_expense_record_change() from public, anon, authenticated;

