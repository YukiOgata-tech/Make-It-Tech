create table mit.expense_categories (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 80),
  color text not null default 'slate'
    check (color in ('slate', 'sky', 'emerald', 'amber', 'orange', 'rose', 'violet', 'cyan')),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (entity_id, id)
);

create unique index expense_categories_entity_name_key
  on mit.expense_categories (entity_id, lower(name));

create table mit.expense_records (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  receipt_number bigint generated by default as identity,
  transaction_date date,
  merchant_name text check (merchant_name is null or length(trim(merchant_name)) between 1 and 160),
  amount_yen bigint check (amount_yen is null or amount_yen > 0),
  tax_amount_yen bigint check (
    tax_amount_yen is null
    or (tax_amount_yen >= 0 and amount_yen is not null and tax_amount_yen <= amount_yen)
  ),
  category_id uuid,
  payment_method text check (
    payment_method is null
    or payment_method in ('cash', 'credit_card', 'bank_transfer', 'e_money', 'other')
  ),
  description text check (description is null or length(description) <= 500),
  memo text check (memo is null or length(memo) <= 2000),
  document_source text not null default 'paper_scan'
    check (document_source in ('paper_scan', 'electronic', 'other')),
  status text not null default 'draft'
    check (status in ('draft', 'confirmed', 'archived')),
  created_by uuid not null references mit.app_users(user_id),
  updated_by uuid not null references mit.app_users(user_id),
  confirmed_by uuid references mit.app_users(user_id),
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (entity_id, id),
  unique (entity_id, receipt_number),
  constraint expense_records_category_same_entity
    foreign key (entity_id, category_id)
    references mit.expense_categories(entity_id, id),
  constraint expense_records_confirmed_fields_check check (
    status <> 'confirmed'
    or (
      transaction_date is not null
      and merchant_name is not null
      and length(trim(merchant_name)) > 0
      and amount_yen is not null
      and amount_yen > 0
      and confirmed_by is not null
      and confirmed_at is not null
    )
  )
);

create index expense_records_entity_date_idx
  on mit.expense_records (entity_id, transaction_date desc, created_at desc);
create index expense_records_entity_status_idx
  on mit.expense_records (entity_id, status, created_at desc);
create index expense_records_entity_category_idx
  on mit.expense_records (entity_id, category_id, transaction_date desc);
create index expense_records_entity_amount_idx
  on mit.expense_records (entity_id, amount_yen);

create table mit.expense_receipt_files (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  expense_id uuid not null,
  storage_bucket text not null default 'mit-expense-receipts'
    check (storage_bucket = 'mit-expense-receipts'),
  storage_path text not null unique,
  original_filename text not null check (length(trim(original_filename)) between 1 and 255),
  mime_type text not null
    check (mime_type in ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  file_size_bytes bigint not null check (file_size_bytes > 0 and file_size_bytes <= 15728640),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  is_primary boolean not null default false,
  uploaded_by uuid not null references mit.app_users(user_id),
  created_at timestamptz not null default now(),
  unique (entity_id, id),
  constraint expense_receipt_files_expense_same_entity
    foreign key (entity_id, expense_id)
    references mit.expense_records(entity_id, id)
    on delete cascade
);

create index expense_receipt_files_expense_idx
  on mit.expense_receipt_files (entity_id, expense_id, created_at);
create unique index expense_receipt_files_one_primary_idx
  on mit.expense_receipt_files (entity_id, expense_id)
  where is_primary;

create table mit.expense_activity_logs (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  expense_id uuid not null,
  action text not null check (action in ('created', 'updated', 'confirmed', 'archived', 'restored')),
  changes jsonb not null default '{}'::jsonb,
  performed_by uuid references mit.app_users(user_id),
  created_at timestamptz not null default now(),
  constraint expense_activity_logs_expense_same_entity
    foreign key (entity_id, expense_id)
    references mit.expense_records(entity_id, id)
    on delete cascade
);

create index expense_activity_logs_expense_idx
  on mit.expense_activity_logs (entity_id, expense_id, created_at desc);

