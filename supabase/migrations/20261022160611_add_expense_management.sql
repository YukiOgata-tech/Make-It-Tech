create function mit.protect_expense_record_immutable_fields()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.id = old.id;
  new.entity_id = old.entity_id;
  new.receipt_number = old.receipt_number;
  new.created_by = old.created_by;
  new.created_at = old.created_at;
  return new;
end;
$$;

