create function mit.protect_sales_record_immutable_fields()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.id = old.id;
  new.entity_id = old.entity_id;
  new.sales_number = old.sales_number;
  new.created_by = old.created_by;
  new.created_at = old.created_at;
  if old.status = 'confirmed' and new.status = 'confirmed' then
    new.confirmed_by = old.confirmed_by;
    new.confirmed_at = old.confirmed_at;
  end if;
  return new;
end;
$$;

create trigger sales_records_protect_immutable_fields
before update on mit.sales_records for each row execute function mit.protect_sales_record_immutable_fields();

create function mit.protect_sales_payment_history()
returns trigger language plpgsql set search_path = '' as $$
begin
  if old.status <> 'recorded' or new.status <> 'voided' or
     (new.id, new.entity_id, new.sale_id, new.paid_on, new.amount_yen,
      new.method, new.destination, new.notes, new.created_by, new.created_at)
       is distinct from
     (old.id, old.entity_id, old.sale_id, old.paid_on, old.amount_yen,
      old.method, old.destination, old.notes, old.created_by, old.created_at) then
    raise exception 'A payment can only be voided; its details cannot be changed';
  end if;
  return new;
end;
$$;

create trigger sales_payments_protect_history
before update on mit.sales_payments for each row execute function mit.protect_sales_payment_history();

create function mit.validate_sale_payment_total()
returns trigger language plpgsql set search_path = '' as $$
declare
  target_sale_id uuid;
  sale mit.sales_records%rowtype;
  paid_total numeric;
begin
  if tg_table_name = 'sales_records' then
    target_sale_id := new.id;
  else
    target_sale_id := new.sale_id;
  end if;
  select * into sale from mit.sales_records where id = target_sale_id for update;
  if not found then return null; end if;
  select coalesce(sum(amount_yen), 0) into paid_total
    from mit.sales_payments where sale_id = target_sale_id and status = 'recorded';
  if paid_total > 0 and sale.status <> 'confirmed' then
    raise exception 'Payments require a confirmed sale';
  end if;
  if paid_total > coalesce(sale.amount_yen, 0) then
    raise exception 'Payments exceed sale amount';
  end if;
  return null;
end;
$$;

create trigger sales_payments_validate_total
after insert or update on mit.sales_payments
for each row execute function mit.validate_sale_payment_total();
create trigger sales_records_validate_payment_total
after update of amount_yen, status on mit.sales_records
for each row execute function mit.validate_sale_payment_total();

