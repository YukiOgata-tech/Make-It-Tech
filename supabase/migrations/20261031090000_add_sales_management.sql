create table mit.sales_records (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  sales_number bigint generated by default as identity,
  recognized_on date,
  customer_name text check (customer_name is null or length(trim(customer_name)) between 1 and 160),
  title text check (title is null or length(trim(title)) between 1 and 200),
  amount_yen bigint check (amount_yen is null or amount_yen > 0),
  tax_amount_yen bigint check (tax_amount_yen is null or (tax_amount_yen >= 0 and amount_yen is not null and tax_amount_yen <= amount_yen)),
  invoice_number text check (invoice_number is null or length(invoice_number) <= 100),
  invoice_issued_on date,
  invoice_due_on date,
  notes text check (notes is null or length(notes) <= 2000),
  status text not null default 'draft' check (status in ('draft', 'confirmed')),
  created_by uuid not null references mit.app_users(user_id),
  updated_by uuid not null references mit.app_users(user_id),
  confirmed_by uuid references mit.app_users(user_id),
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (entity_id, id),
  unique (entity_id, sales_number),
  constraint sales_confirmed_fields_check check (
    status <> 'confirmed' or (
      recognized_on is not null and customer_name is not null and title is not null
      and amount_yen is not null and confirmed_by is not null and confirmed_at is not null
    )
  )
);

create index sales_records_entity_recognized_idx on mit.sales_records (entity_id, recognized_on desc);
create index sales_records_entity_status_idx on mit.sales_records (entity_id, status, created_at desc);

create table mit.sales_payments (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  sale_id uuid not null,
  paid_on date not null,
  amount_yen bigint not null check (amount_yen > 0),
  method text not null default 'bank_transfer' check (method in ('bank_transfer', 'cash', 'card', 'other')),
  destination text check (destination is null or length(destination) <= 160),
  notes text check (notes is null or length(notes) <= 1000),
  status text not null default 'recorded' check (status in ('recorded', 'voided')),
  created_by uuid not null references mit.app_users(user_id),
  voided_by uuid references mit.app_users(user_id),
  voided_at timestamptz,
  created_at timestamptz not null default now(),
  unique (entity_id, sale_id, id),
  foreign key (entity_id, sale_id) references mit.sales_records(entity_id, id) on delete cascade,
  constraint sales_payment_void_check check (
    (status = 'recorded' and voided_by is null and voided_at is null)
    or (status = 'voided' and voided_by is not null and voided_at is not null)
  )
);

create index sales_payments_sale_idx on mit.sales_payments (entity_id, sale_id, paid_on);
create index sales_payments_entity_date_idx on mit.sales_payments (entity_id, status, paid_on desc);

create table mit.sales_documents (
  id uuid primary key default gen_random_uuid(),
  entity_id uuid not null references mit.entities(id) on delete cascade,
  sale_id uuid not null,
  payment_id uuid,
  kind text not null check (kind in ('invoice', 'payment_proof', 'other')),
  title text not null check (length(trim(title)) between 1 and 200),
  storage_bucket text check (storage_bucket is null or storage_bucket = 'mit-sales-documents'),
  storage_path text unique,
  external_url text check (external_url is null or (length(external_url) <= 2048 and external_url ~ '^https://')),
  original_filename text,
  mime_type text check (mime_type is null or mime_type in ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  file_size_bytes bigint check (file_size_bytes is null or (file_size_bytes > 0 and file_size_bytes <= 15728640)),
  sha256 text check (sha256 is null or sha256 ~ '^[0-9a-f]{64}$'),
  uploaded_by uuid not null references mit.app_users(user_id),
  created_at timestamptz not null default now(),
  foreign key (entity_id, sale_id) references mit.sales_records(entity_id, id) on delete cascade,
  foreign key (entity_id, sale_id, payment_id) references mit.sales_payments(entity_id, sale_id, id),
  constraint sales_document_location_check check (
    (external_url is not null and storage_path is null and storage_bucket is null)
    or (external_url is null and storage_path is not null and storage_bucket = 'mit-sales-documents'
      and original_filename is not null and mime_type is not null and file_size_bytes is not null and sha256 is not null)
  ),
  constraint sales_document_payment_check check ((kind = 'payment_proof') = (payment_id is not null))
);

create index sales_documents_sale_idx on mit.sales_documents (entity_id, sale_id, created_at);
create index sales_documents_payment_idx on mit.sales_documents (entity_id, payment_id) where payment_id is not null;

